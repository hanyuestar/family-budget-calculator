// 不重复抽取 n 张（Fisher-Yates 局部洗牌）
function drawCards(n) {
  var pool = CARDS.slice()
  for (var i = pool.length - 1; i > 0; i--) {
    var j = Math.floor(Math.random() * (i + 1))
    var t = pool[i]; pool[i] = pool[j]; pool[j] = t
  }
  var picked = pool.slice(0, n)
  return picked.map(function (c) {
    var reversed = Math.random() < 0.5
    var ori = reversed ? c.rev : c.up
    return {
      idx: c.idx, slug: c.slug, cn: c.cn, en: c.en, img: c.img,
      reversed: reversed,
      orientation: reversed ? '逆位' : '正位',
      kw: ori.kw,
      text: ori.text,
      today: c.today
    }
  })
}

